/**
 * 빌드 환경 판별 — **백엔드가 없는 빌드**를 명시 플래그로 구분한다.
 *
 * 왜 필요한가: 공개 페이지는 prerender 시점에 백엔드를 부른다. 그런데 빌드가 도는 자리는 둘이고 요구가 정반대다.
 *
 * - **게이트 CI**(`.github/workflows/ci.yml`) — 러너에 백엔드가 없다. "빌드가 통과하는 소스인가"만 보므로
 *   백엔드 불통은 정상 조건이고, 여기서 죽으면 게이트가 상시 red 가 된다.
 * - **테넌트 서빙 빌드** — 백엔드가 살아 있어야 정상이다. 불통이면 **빨리 죽는 게 맞다**: 그대로 구우면
 *   콘텐츠가 빠진 아티팩트가 배포되고, 장애가 "빈 사이트"로 위장돼 아무도 못 알아챈다.
 *
 * 상태값으로는 이 둘을 구분할 수 없다(운영 장애와 러너의 백엔드 부재가 같은 신호로 온다). 그래서 **부르는 쪽이
 * 선언한다** — CI 만 이 플래그를 켠다. 기본값(미설정)은 fail-fast 다.
 *
 * ⚠ **지금 이 트리에는 소스 호출자가 없다.** 유일한 호출자가 홈의 `getPage` 폴백이었는데, 콘텐츠가
 * 소스로 오면서(어휘 계약 rev 4 `contentFile`) 그 왕복 자체가 사라졌다 — 남은 백엔드 호출은 전부
 * `.catch()` 로 fail-soft 라 애초에 빌드를 세우지 않는다. env·CI 배선(`ZALKERA_OFFLINE_BUILD`)과
 * `scripts/verify-zip.mjs`·`snapshot-preview.mjs` 는 그대로 그 플래그를 켠다(무해). **"빌드 시점
 * 백엔드 불통을 무엇으로 감지할 것인가"는 다시 열린 물음이고, 이 헬퍼를 지울지 새 tripwire 를 걸지는
 * 별건이다** — 여기 안 적으면 다음 사람이 "쓰이는 장치"로 읽는다.
 */
export function isOfflineBuild(): boolean {
    return process.env.ZALKERA_OFFLINE_BUILD === "1";
}
