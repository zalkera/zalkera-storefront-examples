/**
 * **레포 자기 검사 축** — 이 레포에 커밋된 자격증명을 찾는다(`credential-literals.mjs`).
 *
 * ⚠ **위 표와 보정이 다르다. 그것이 설계다.**
 *   · [SECRET_CONTENT] 는 **고객 납품 zip** 을 본다. 거기서 오탐의 대가는 파일 하나가 팩에서
 *     빠지는 것이고 도구가 이유를 말해 준다 — 그래서 느슨하게 잡는 편이 낫다.
 *   · 이 표는 **우리 레포**를 본다. 여기서 오탐의 대가는 **CI 가 빨개지는 것**이고, 이 레포는
 *     탐지기의 시험 픽스처로 가득하다(접두 + 짧은 자리표시자 꼴이 여럿). 느슨하게 잡으면 정상
 *     픽스처가 줄줄이 걸려 검사기를 끄게 된다.
 *     ⚠ **여기에 그 꼴을 예시로 적지 마라.** 이 파일은 zip 에 실려 [SECRET_CONTENT] 의
 *       스캔 대상이 된다 — 예시 한 줄이 **전 팩을 거짓 반려**시킨다(실증). 파일 머리
 *       `verify-zip.mjs` 의 같은 경고와 한 규칙이다.
 *   그래서 여기서는 **진짜 키 꼴**만 본다: `oqsk_` 는 실물 그대로 base62 **43자**
 *   (`StorefrontKeyCodec.PREFIX` + 43), PEM 은 헤더가 아니라 **본문이 뒤따르는 블록**.
 *
 * ⚠ 나머지 종은 위 표를 그대로 쓴다 — 두 벌로 만들지 않는다.
 */
export const REPO_LITERALS = SECRET_CONTENT.map(([what, re]) => {
    if (what === "잘커라 스토어프론트 키") return [what, /\boqsk_[0-9A-Za-z]{43}\b/];
    // 헤더 다음에 base64 본문이 와야 진짜 키다. 헤더 문자열만 든 파싱·시험 코드는 키가 아니다.
    // ⚠ **하한이 48 인 이유**: Ed25519/X25519 PKCS#8 개인키는 본문이 **정확히 64자 한 줄**이다.
    //   100 으로 두면 그 실물이 통째로 샌다(실증 — `openssl genpkey -algorithm ed25519`).
    //   RSA·EC 는 훨씬 길어 영향 없고, 시험 픽스처의 본문(수 자)은 여전히 안 걸린다.
    // 개행은 실개행과 **이스케이프 개행**(JSON·env 한 줄) 둘 다 받는다.
    // ⚠ **본문 안에도** 이스케이프 개행이 온다 — PEM 은 64자로 감기므로 한 줄 JSON 에서는
    //   본문 중간에 `\r`·`\n` 이 흩어진다. 구분자에만 넣고 본문에 안 넣으면 감긴 키를 놓친다.
    if (what === "개인키 블록") return [what, /-----BEGIN [A-Z ]{0,20}PRIVATE KEY-----(?:\s|\\r|\\n)*(?:[A-Za-z0-9+/=\s]|\\r|\\n){48,}/];
    return [what, re];
});
